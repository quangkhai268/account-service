-- Schema PostgreSQL (10+) cho account-server

CREATE TABLE account (
    acct_no        VARCHAR(12)   NOT NULL,
    cif_no         VARCHAR(20),
    id_no          VARCHAR(40),
    acct_type      VARCHAR(4),
    acct_title     VARCHAR(255),
    curr_code      VARCHAR(3),
    branch_code    VARCHAR(6),
    ledger_balance NUMERIC(19,2),
    min_balance    NUMERIC(19,2),
    acc_status     VARCHAR(1),   -- 0 Active,1 Inactive,2 Dormant,3 Escheat,4 Closed,5 Close Out in Process
    CONSTRAINT pk_account PRIMARY KEY (acct_no)
);
CREATE INDEX idx_account_cif ON account (cif_no);
CREATE INDEX idx_account_id  ON account (id_no);

-- Log request/response của API. dedup_key (appCode|requestId) UNIQUE để chặn trùng requestId;
-- request bị từ chối vì trùng có dedup_key = NULL (PostgreSQL cho phép nhiều NULL trong UNIQUE)
-- nên vẫn ghi log được.
CREATE TABLE api_request_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    request_id      VARCHAR(50),
    app_code        VARCHAR(20),
    dedup_key       VARCHAR(80),
    request_time    TIMESTAMP NOT NULL,
    request_body    TEXT,
    response_time   TIMESTAMP,
    response_body   TEXT,
    tran_status     VARCHAR(1),
    error_code      VARCHAR(100),
    process_time_ms BIGINT,
    CONSTRAINT pk_api_request_log PRIMARY KEY (id),
    CONSTRAINT uk_api_request_log_dedup UNIQUE (dedup_key)
);
CREATE INDEX idx_api_request_log_req  ON api_request_log (request_id);
CREATE INDEX idx_api_request_log_time ON api_request_log (request_time);

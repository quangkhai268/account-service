-- Schema PostgreSQL (10+) cho account-client

CREATE TABLE api_call_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    request_id    VARCHAR(50)   NOT NULL,
    app_code      VARCHAR(20),
    endpoint      VARCHAR(500),
    request_time  TIMESTAMP     NOT NULL,
    request_body  TEXT,
    response_time TIMESTAMP,
    response_body TEXT,
    http_status   INTEGER,
    tran_status   VARCHAR(1),    -- 0 success, 1 fail, 2 timeout
    tran_desc     VARCHAR(200),
    error_code    VARCHAR(100),
    status        VARCHAR(10)   NOT NULL,   -- PENDING / SUCCESS / FAILED / TIMEOUT
    duration_ms   BIGINT,
    CONSTRAINT pk_api_call_log PRIMARY KEY (id)
);
CREATE UNIQUE INDEX ux_api_call_log_req ON api_call_log (request_id);

CREATE TABLE account_info (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    request_id     VARCHAR(50)  NOT NULL,
    cif_no         VARCHAR(20),
    id_no          VARCHAR(40),
    acct_no        VARCHAR(12),
    acct_type      VARCHAR(4),
    acct_title     VARCHAR(255),
    curr_code      VARCHAR(3),
    branch_code    VARCHAR(6),
    ledger_balance NUMERIC(19,2),
    min_balance    NUMERIC(19,2),
    acc_status     VARCHAR(1),
    created_at     TIMESTAMP    NOT NULL,
    CONSTRAINT pk_account_info PRIMARY KEY (id)
);
CREATE INDEX idx_account_info_req  ON account_info (request_id);
CREATE INDEX idx_account_info_acct ON account_info (acct_no);
